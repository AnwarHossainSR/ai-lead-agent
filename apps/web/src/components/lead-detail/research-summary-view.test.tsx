import { render, screen } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import type { ResearchSummary } from "@/lib/lead-detail";
import { ResearchSummaryView } from "./research-summary-view";

const SUMMARY: ResearchSummary = {
  id: "summary-1",
  sections: {
    business: [{ text: "Runs a mid-size logistics operation in Dubai.", cites: ["o1"] }],
    webPresence: [],
    opportunities: [],
    people: [],
    approach: [],
  },
  unknownFacts: ["Annual revenue"],
  createdAt: "2026-01-01T00:00:00Z",
};

describe("ResearchSummaryView", () => {
  it("wraps generated prose with the persistent Generated label", () => {
    render(<ResearchSummaryView summary={SUMMARY} />);

    expect(screen.getByText("Generated by model")).toBeInTheDocument();
    expect(screen.getByText("Runs a mid-size logistics operation in Dubai.")).toBeInTheDocument();
  });

  it("renders a derived unknown fact as the word unknown, not a blank", () => {
    render(<ResearchSummaryView summary={SUMMARY} />);

    expect(screen.getByText(/Annual revenue:/)).toBeInTheDocument();
    expect(screen.getByText("unknown")).toBeInTheDocument();
  });

  it("shows an explicit state when no summary has been generated", () => {
    render(<ResearchSummaryView summary={null} />);

    // An absence stated in words, never a blank region the reader has to
    // interpret (spec: empty state).
    expect(screen.getByText("No research summary yet")).toBeInTheDocument();
    expect(screen.getByText(/This is an absence, not an empty summary/)).toBeInTheDocument();
  });
});
