import type { ReactNode } from "react";

import { cn } from "@/lib/utils";

interface GeneratedProps {
  /** The model-produced prose to render — a research summary, a draft. */
  children: ReactNode;
  className?: string;
}

/**
 * Wraps model-produced prose with a label that stays visible for as long
 * as the content is on the page — never a one-time toast or a label that
 * can scroll out alongside the text it describes.
 */
export function Generated({ children, className }: GeneratedProps) {
  return (
    <div data-slot="generated" className={cn("space-y-1.5", className)}>
      <span className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
        Generated by model
      </span>
      <div>{children}</div>
    </div>
  );
}
