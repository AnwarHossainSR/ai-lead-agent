import { SparklesIcon } from "lucide-react";
import type { ReactNode } from "react";

import { cn } from "@/lib/utils";

interface GeneratedProps {
  /** The model-produced prose to render — a research summary, a draft. */
  children: ReactNode;
  className?: string;
}

/**
 * Wraps model-produced prose with a label that stays visible for as long
 * as the content is on the page — never a one-time toast or a label that
 * can scroll out alongside the text it describes.
 *
 * The rail and the tinted surface keep the boundary of the generated text
 * obvious even where the label has scrolled past, so nothing inside it can be
 * read as an observed fact.
 */
export function Generated({ children, className }: GeneratedProps) {
  return (
    <div
      data-slot="generated"
      className={cn(
        "space-y-1.5 rounded-r-lg border-l-2 border-info/50 bg-info-subtle/40 py-2 pr-2 pl-3",
        className,
      )}
    >
      <span className="flex items-center gap-1.5 text-xs font-medium tracking-wide text-info uppercase">
        <SparklesIcon className="size-3" aria-hidden="true" />
        Generated by model
      </span>
      <div className="text-sm">{children}</div>
    </div>
  );
}
