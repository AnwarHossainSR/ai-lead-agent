import { render, screen } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import { Generated } from "./generated";

describe("Generated", () => {
  it("labels model-produced prose persistently alongside the content", () => {
    render(<Generated>This company appears to be modernizing its stack.</Generated>);

    expect(screen.getByText("Generated by model")).toBeInTheDocument();
    expect(
      screen.getByText("This company appears to be modernizing its stack."),
    ).toBeInTheDocument();
  });

  it("keeps the label attached to the block it describes after the restyle", () => {
    const { container } = render(<Generated>A drafted opening line.</Generated>);

    const block = container.querySelector("[data-slot=generated]");
    expect(block).toHaveTextContent("Generated by model");
    expect(block).toHaveTextContent("A drafted opening line.");
    // The rail keeps the boundary of the generated text visible on its own.
    expect(block?.className).toContain("border-l-2");
  });

  it("does not let generated prose read as an observed fact", () => {
    const { container } = render(<Generated>A drafted opening line.</Generated>);

    const block = container.querySelector("[data-slot=generated]");
    expect(block?.className).not.toBe("");
    expect(block?.className).not.toMatch(/#[0-9a-f]{3,8}|rgb\(|oklch\(/i);
    expect(screen.getByText("Generated by model")).toBeVisible();
  });
});
